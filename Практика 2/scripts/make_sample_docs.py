"""Генерирует тестовые регламенты в PDF и DOCX для демонстрации ingestion
из разных форматов (запускается один раз, результат коммитится в docs/)."""
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from docx import Document
import textwrap
import glob

FONT_PATH = glob.glob("/usr/share/fonts/**/DejaVuSans.ttf", recursive=True)
pdfmetrics.registerFont(TTFont("DejaVu", FONT_PATH[0]))

PDF_TEXT = """РЕГЛАМЕНТ ДОСТУПА К ДАННЫМ

1. Общие положения
Регламент определяет порядок предоставления сотрудникам доступа к корпоративным
базам данных и хранилищам.

2. Уровни доступа
2.1. Базовый доступ выдаётся автоматически при оформлении сотрудника и даёт право
читать только обезличенные данные.
2.2. Расширенный доступ к персональным данным клиентов выдаётся по заявке,
согласованной руководителем и службой безопасности, срок рассмотрения — 3 рабочих дня.
2.3. Административный доступ к продуктивным базам данных выдаётся только
инженерам сопровождения и требует согласования директора по безопасности.

3. Порядок предоставления доступа
3.1. Заявка подаётся через внутренний портал с указанием цели и срока действия.
3.2. Доступ выдаётся на срок не более 90 дней, далее требуется продление.
3.3. Все действия с расширенным и административным доступом логируются и хранятся
не менее одного года.

4. Отзыв доступа
4.1. Доступ отзывается немедленно при увольнении сотрудника.
4.2. Доступ отзывается, если сотрудник не продлил заявку по истечении 90 дней.
4.3. Служба безопасности проводит ежеквартальный аудит выданных прав доступа.

5. Ответственность
5.1. Передача своих учётных данных другому сотруднику запрещена.
5.2. Нарушение регламента рассматривается службой безопасности в индивидуальном
порядке и может повлечь ограничение доступа ко всем системам компании.
"""

def make_pdf(path: str) -> None:
    c = canvas.Canvas(path, pagesize=A4)
    width, height = A4
    c.setFont("DejaVu", 11)
    y = height - 50
    for raw_line in PDF_TEXT.split("\n"):
        wrapped = textwrap.wrap(raw_line, width=95) or [""]
        for line in wrapped:
            if y < 50:
                c.showPage()
                c.setFont("DejaVu", 11)
                y = height - 50
            c.drawString(50, y, line)
            y -= 16
    c.save()


def make_docx(path: str) -> None:
    doc = Document()
    doc.add_heading("РЕГЛАМЕНТ ОТПУСКОВ", level=1)

    doc.add_heading("1. Общие положения", level=2)
    doc.add_paragraph(
        "Регламент определяет порядок планирования, согласования и переноса "
        "ежегодных оплачиваемых отпусков сотрудников компании."
    )

    doc.add_heading("2. Планирование отпусков", level=2)
    doc.add_paragraph(
        "2.1. График отпусков на год формируется руководителями отделов до 15 декабря "
        "предыдущего года и утверждается отделом кадров."
    )
    doc.add_paragraph(
        "2.2. Минимальная продолжительность одной части отпуска — 14 календарных дней."
    )
    doc.add_paragraph(
        "2.3. Отпуск за текущий рабочий год можно разбивать не более чем на 3 части."
    )

    doc.add_heading("3. Перенос отпуска", level=2)
    doc.add_paragraph(
        "3.1. Перенос отпуска согласовывается с руководителем не позднее чем за "
        "7 рабочих дней до даты начала отпуска по графику."
    )
    doc.add_paragraph(
        "3.2. Перенос отпуска по производственной необходимости допускается не более "
        "одного раза в год и требует письменного согласия сотрудника."
    )

    doc.add_heading("4. Компенсация и отзыв из отпуска", level=2)
    doc.add_paragraph(
        "4.1. Денежная компенсация вместо отпуска выплачивается только при увольнении "
        "за неиспользованные дни."
    )
    doc.add_paragraph(
        "4.2. Отзыв сотрудника из отпуска допускается только с его письменного согласия; "
        "неиспользованные дни переносятся по соглашению сторон."
    )

    doc.save(path)


if __name__ == "__main__":
    make_pdf("/out/reglament_data_access.pdf")
    make_docx("/out/reglament_otpuska.docx")
    print("Generated reglament_data_access.pdf and reglament_otpuska.docx")
